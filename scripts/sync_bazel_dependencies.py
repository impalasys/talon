#!/usr/bin/env python3
"""Keep Bazel's optional dependency metadata aligned with the Cargo project."""

import argparse
import json
from pathlib import Path
import tomllib


ROOT = Path(__file__).absolute().parents[1]
BAZEL_DIR = ROOT / "tools" / "bazel"
FEATURES = ("aws", "rocksdb", "cpu-profile", "heap-profile")


def manifest() -> str:
    cargo = tomllib.loads((ROOT / "Cargo.toml").read_text())
    dependencies = sorted({
        dependency.removeprefix("dep:")
        for feature in FEATURES
        for dependency in cargo["features"][feature]
        if dependency.startswith("dep:")
    })
    lines = [
        "# Generated by scripts/sync_bazel_dependencies.py; do not edit.",
        "# Resolve optional dependencies without changing Cargo's default features.",
        "[package]",
        'name = "talon-bazel-features"',
        'version = "0.0.0"',
        'edition = "2021"',
        "publish = false",
        "",
        "[lib]",
        'path = "features.rs"',
        "",
        "[dependencies]",
    ]
    for name in dependencies:
        value = cargo["dependencies"][name]
        if isinstance(value, dict):
            value = dict(value)
            forwarded = {item.split("/", 1)[1] for feature in FEATURES for item in cargo["features"][feature] if item.startswith(name + "/")}
            if forwarded:
                value["features"] = sorted(set(value.get("features", [])) | forwarded)
            fields = ", ".join(
                f"{key} = {json.dumps(item)}"
                for key, item in value.items()
                if key != "optional"
            )
            lines.append(f"{name} = {{ {fields} }}")
        else:
            lines.append(f"{name} = {json.dumps(value)}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = manifest()
    if args.check:
        if (BAZEL_DIR / "Cargo.toml").read_text() != expected:
            parser.exit(1, "Bazel dependency metadata is stale. Run python3 scripts/sync_bazel_dependencies.py, then bazel build //:binaries.\n")
        return
    (BAZEL_DIR / "Cargo.toml").write_text(expected)


if __name__ == "__main__":
    main()
