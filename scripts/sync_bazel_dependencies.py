#!/usr/bin/env python3
"""Keep Bazel's optional dependency metadata aligned with the Cargo project."""

import argparse
import json
from pathlib import Path
import tomllib


ROOT = Path(__file__).absolute().parents[1]
BAZEL_DIR = ROOT / "tools" / "bazel"
FEATURES = ("aws", "rocksdb", "cpu-profile", "heap-profile")


def feature_dependencies():
    """Resolve native feature dependencies through internal path packages."""
    found = {}
    visited = set()

    def add(name, value, feature=None):
        value = dict(value) if isinstance(value, dict) else {"version": value}
        value.pop("optional", None)
        features = set(value.pop("features", []))
        if feature:
            features.add(feature)
        previous = found.get(name)
        if previous:
            prior = dict(previous)
            features.update(prior.pop("features", []))
            if prior != value:
                raise ValueError(f"Conflicting feature dependency declarations for {name}")
        if features:
            value["features"] = sorted(features)
        found[name] = value

    def visit(path, selected):
        cargo = tomllib.loads(path.read_text())
        key = (str(path), tuple(sorted(selected)))
        if key in visited:
            return
        visited.add(key)
        dependencies = cargo.get("dependencies", {})
        # A selected optional package owns its regular external dependencies.
        # Internal packages have their own crate-universe workspace metadata.
        if path != ROOT / "Cargo.toml":
            for name, value in dependencies.items():
                if not isinstance(value, dict) or not value.get("optional", False):
                    if not isinstance(value, dict) or "path" not in value:
                        add(name, value)
        pending = list(selected)
        expanded = set()
        while pending:
            feature = pending.pop()
            if feature in expanded:
                continue
            expanded.add(feature)
            for item in cargo.get("features", {}).get(feature, []):
                if item.startswith("dep:") or "/" in item:
                    name, _, forwarded = item.removeprefix("dep:").partition("/")
                    name = name.removesuffix("?")
                    value = dependencies[name]
                    if isinstance(value, dict) and "path" in value:
                        child = (path.parent / value["path"] / "Cargo.toml").resolve()
                        child_features = list(value.get("features", []))
                        if value.get("default-features", True):
                            child_features.append("default")
                        if forwarded:
                            child_features.append(forwarded)
                        visit(child, child_features)
                    else:
                        add(name, value, forwarded or None)
                else:
                    pending.append(item)

    visit(ROOT / "Cargo.toml", FEATURES)
    return found


def manifest() -> str:
    dependencies = feature_dependencies()
    lines = [
        "# Generated by scripts/sync_bazel_dependencies.py; do not edit.",
        "# Resolve optional dependencies without changing Cargo's default features.",
        "[package]",
        'name = "talon-bazel-features"',
        'version = "0.0.0"',
        'edition = "2021"',
        "publish = false",
        "",
        "[lib]",
        'path = "features.rs"',
        "",
        "[dependencies]",
    ]
    for name, value in sorted(dependencies.items()):
        fields = ", ".join(f"{key} = {json.dumps(item)}" for key, item in value.items())
        lines.append(f"{name} = {{ {fields} }}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = manifest()
    if args.check:
        if (BAZEL_DIR / "Cargo.toml").read_text() != expected:
            parser.exit(1, "Bazel dependency metadata is stale. Run python3 scripts/sync_bazel_dependencies.py, then bazel build //:binaries.\n")
        return
    (BAZEL_DIR / "Cargo.toml").write_text(expected)


if __name__ == "__main__":
    main()
